def _to_table(name: str, rows: list[dict[str, Any]]) -> Any:
    import pyarrow as pa

    schema = TABLES[name].arrow_schema()
    cols = {f.name: [r.get(f.name) for r in rows] for f in schema}
    table = pa.Table.from_pydict(cols, schema=schema)
    return table.sort_by([(k, "ascending") for k in TABLES[name].key])


def _sorted(table: Any, name: str) -> Any:
    return table.sort_by([(k, "ascending") for k in TABLES[name].key])


def import_legacy(
    source_root: Path,
    context: RunContext,
    *,
    config_dir: Path | None = None,
) -> DatasetCandidate:
    """Import the legacy corpus under ``source_root`` into a new snapshot candidate.

    ``config_dir`` defaults to the package repository ``config/`` (team/venue aliases).
    Never mutates ``source_root``. Returns an unpromoted candidate; validate then promote.
    """
    timings: dict[str, float] = {}
    t0 = time.perf_counter()
    mark = t0

    def tick(label: str) -> None:
        nonlocal mark
        now = time.perf_counter()
        timings[label] = round(now - mark, 3)
        mark = now

    cfg = config_dir or REPO_CONFIG_DIR
    try:
        clubs = ids.ClubRegistry.from_csv(cfg / "team_aliases.csv")
        venues = ids.VenueRegistry.from_csv(cfg / "venue_aliases.csv")
    except (OSError, KeyError, ValueError) as exc:
        raise LegacyImportError(f"invalid identity config in {cfg}: {exc}") from exc
    state = State(clubs=clubs, venues=venues)

    records = _inventory(source_root)
    by_family: dict[str, list[FileRecord]] = defaultdict(list)
    for r in records:
        by_family[r.family].append(r)
    missing = [f for f, mandatory in FAMILIES.items() if mandatory and not by_family.get(f)]
    if missing:
        raise LegacyImportError(f"mandatory legacy families missing under {source_root}: {missing}")
    tick("inventory")

    for fam, reason in IGNORED_REASONS.items():
        for r in by_family.get(fam, []):
            r.disposition, r.reason = "ignored", reason
    for r in by_family.get("unknown", []):
        r.disposition, r.reason = "quarantined", "unrecognized file family; preserved by path/hash"
        state.issues.add(
            "unknown_file_family",
            Severity.WARNING,
            f"unrecognized legacy file {r.path}",
            table="source_files",
            row_key=r.path,
            source_path=r.path,
        )

    match_rows = _import_matches(state, by_family["matches"], opponent_evidence(by_family["player_performance"]))
    tick("matches")
    evidence = _load_evidence({r.path: r for r in by_family.get("identity_evidence", [])})
    player_rows, alias_rows = _import_players(
        state, by_family["player_performance"], by_family.get("player_personal", []), evidence
    )
    tick("players")
    pg_table = _import_player_games(state, by_family["player_performance"])
    for r in (*by_family["player_performance"], *by_family.get("player_personal", [])):
        r.data = b""  # release ~170 MB of raw bytes once parsed
    tick("player_games")
    lineup_table = _import_lineups(state, by_family.get("lineups", []))
    tick("lineups")
    drafts, schools = _import_drafts(state, by_family)
    contracts = _import_contracts(state, by_family.get("contracts", []))
    live = _import_live(state, by_family)
    preds = _import_predictions(state, by_family.get("legacy_predictions", []))
    rank_scores, rank_yearly, bios = _import_rankings(state, by_family)
    tick("other_families")

    # seasons
    seasons: dict[int, dict[str, Any]] = {}
    for m in match_rows:
        s = seasons.setdefault(
            m["season"],
            {
                "season": m["season"],
                "first_match_date": None,
                "last_match_date": None,
                "matches_complete": 0,
                "matches_scheduled": 0,
                "fixture_checked_at": None,
                "schedule_complete": None,
                "source_status": None,
            },
        )
        d = m["match_date"]
        if d is not None:
            s["first_match_date"] = min(filter(None, [s["first_match_date"], d]))
            s["last_match_date"] = max(filter(None, [s["last_match_date"], d]))
        s["matches_complete"] += m["status"] == MatchStatus.COMPLETE.value
        s["matches_scheduled"] += m["status"] == MatchStatus.SCHEDULED.value

    venue_rows = venues.venue_rows(state.accounting.get("venues_observed", {}))
    source_file_rows = [r.as_report() for r in records]

    builder = SnapshotBuilder(context.data_root, clock=context.clock, code_version=IMPORTER_VERSION, run_id=None)
    tables: dict[str, Any] = {
        "players": _to_table("players", player_rows),
        "player_aliases": _to_table("player_aliases", alias_rows),
        "clubs": _to_table("clubs", clubs.club_rows()),
        "club_aliases": _to_table("club_aliases", clubs.alias_rows()),
        "venues": _to_table("venues", venue_rows),
        "seasons": _to_table("seasons", [seasons[k] for k in sorted(seasons)]),
        "matches": _to_table("matches", match_rows),
        "player_games": _sorted(pg_table, "player_games"),
        "lineups": _sorted(lineup_table, "lineups"),
        "draft_events": _to_table("draft_events", drafts),
        "school_observations": _to_table("school_observations", schools),
        "contract_observations": _to_table("contract_observations", contracts),
        "live_snapshots": _to_table("live_snapshots", live),
        "legacy_predictions": _to_table("legacy_predictions", preds),
        "legacy_rank_scores": _to_table("legacy_rank_scores", rank_scores),
        "legacy_rank_yearly": _to_table("legacy_rank_yearly", rank_yearly),
        "legacy_top100_bios": _to_table("legacy_top100_bios", bios),
        "quarantine": _to_table("quarantine", list(state.quarantine.rows.values())),
        "quality_issues": _to_table("quality_issues", list(state.issues.rows.values())),
        "source_files": _to_table("source_files", source_file_rows),
    }
    tick("assemble")
    for name, table in tables.items():
        part = TABLES[name].partition_by
        if part and table.num_rows:
            builder.add_partitioned(name, table, part)
        else:
            builder.add(name, table)
    severity_counts = Counter(i["severity"] for i in state.issues.rows.values())
    aggregate = hashlib.sha256("".join(f"{r.path}\0{r.sha256}\n" for r in records).encode()).hexdigest()
    cand = builder.finish(
        status=DatasetStatus.LEGACY_UNVERIFIED,
        source_revisions={"legacy_input_aggregate_sha256": aggregate, "importer": IMPORTER_VERSION},
        quality={k: severity_counts[k] for k in sorted(severity_counts)},
        notes=("legacy import: available_at unknown; dates labelled by date_quality",),
    )
    tick("write_snapshot")

    families: dict[str, dict[str, Any]] = {}
    for fam in FAMILIES:
        rs = by_family.get(fam, [])
        families[fam] = {
            "status": "present" if rs else "absent",
            "files": len(rs),
            "rows_read": sum(r.rows_read or 0 for r in rs),
            "rows_imported": sum(r.rows_imported or 0 for r in rs),
            "rows_quarantined": sum(r.rows_quarantined or 0 for r in rs),
            "dispositions": dict(sorted(Counter(r.disposition for r in rs).items())),
        }
    matches_acc = families["matches"]
    report: dict[str, Any] = {
        "schema_version": 1,
        "importer": IMPORTER_VERSION,
        "snapshot_id": cand.manifest.snapshot_id,
        "status": DatasetStatus.LEGACY_UNVERIFIED.value,
        "source_root": str(source_root),
        "input_aggregate_sha256": aggregate,
        "files": source_file_rows,
        "families": families,
        "tables": {k: v.num_rows for k, v in tables.items()},
        "row_accounting": {
            "matches": {
                "read": matches_acc["rows_read"],
                "imported": matches_acc["rows_imported"],
                "quarantined": matches_acc["rows_quarantined"],
            },
            "player_games": state.accounting["player_games"],
            "lineups": state.accounting.get("lineups", {}),
        },
        "quality_issue_counts": dict(sorted(Counter(i["rule_id"] for i in state.issues.rows.values()).items())),
        "quality_severity_counts": dict(sorted(severity_counts.items())),
        "quarantine_counts": dict(
            sorted(Counter(f"{q['table_name']}:{q['reason']}" for q in state.quarantine.rows.values()).items())
        ),
        "identity": {
            "duplicates": [
                {
                    "duplicate": ids.player_id_for_slug(d.duplicate_slug),
                    "canonical": ids.player_id_for_slug(d.canonical_slug),
                    "source": d.source_url,
                }
                for d in ids.KNOWN_DUPLICATES
            ],
            "verified_source_aliases": len(ids.VERIFIED_SOURCE_ALIASES),
            "players_with_source_urls": sum(1 for p in player_rows if p["source_urls"]),
            "clubs_auto_created": dict(sorted(clubs.created.items())),
        },
        "timings_s": timings,
        "wall_s": round(time.perf_counter() - t0, 3),
    }
    return DatasetCandidate(candidate=cand, report=report, data_root=context.data_root)


def iter_family_paths(report: Mapping[str, Any], family: str) -> Iterable[str]:
    return (f["path"] for f in report["files"] if f["family"] == family)


