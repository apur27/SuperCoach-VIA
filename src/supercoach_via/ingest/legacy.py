def _load_evidence(records: Mapping[str, FileRecord]) -> dict[str, str]:
    """Legacy path -> verified source URL from the refresh reconciliation evidence."""
    rec = records.get(EVIDENCE_REL)
    if rec is None:
        return {}
    data = json.loads(rec.data)
    out: dict[str, str] = {}
    for p in data.get("players", []):
        if p.get("status") == "checked" and p.get("path") and p.get("source"):
            out[p["path"]] = p["source"]
    rec.count(len(data.get("players", [])), len(out), 0)
    rec.rows_imported, rec.rows_quarantined = len(data.get("players", [])), 0
    return out


def _import_players(
    state: State, perf: list[FileRecord], personal: list[FileRecord], evidence: dict[str, str]
) -> tuple[list[dict[str, Any]], list[dict[str, Any]]]:
    personal_by_slug = {r.path.rsplit("/", 1)[-1][: -len(ids.PERSONAL_SUFFIX)]: r for r in personal}
    perf_by_slug = {ids.slug_from_filename(r.path.rsplit("/", 1)[-1]): r for r in perf}
    alias_by_slug = {a.slug: a for a in ids.VERIFIED_SOURCE_ALIASES}
    dup_by_slug = {d.duplicate_slug: d for d in ids.KNOWN_DUPLICATES}
    canon_urls: dict[str, list[str]] = defaultdict(list)
    for d in ids.KNOWN_DUPLICATES:
        canon_urls[d.canonical_slug].append(d.source_url)
    rows: list[dict[str, Any]] = []
    aliases: list[dict[str, Any]] = []
    for slug in sorted(set(perf_by_slug) | set(personal_by_slug)):
        pid = ids.player_id_for_slug(slug)
        prec = perf_by_slug.get(slug)
        drec = personal_by_slug.get(slug)
        first = last = born = debut = height = weight = None
        if drec is not None:
            header, prow = _csv_rows(drec)
            if prow and len(prow[0]) == len(header):
                pd_ = dict(zip(header, prow[0], strict=True))
                first = (pd_.get("first_name") or "").strip() or None
                last = (pd_.get("last_name") or "").strip() or None
                born, debut = pd_.get("born_date"), pd_.get("debut_date")
                height, weight = pd_.get("height"), pd_.get("weight")
                for extra_i, extra in enumerate(prow[1:], start=2):
                    state.quarantine.add("players", "extra_personal_details_row", {"cells": extra}, drec, extra_i)
                drec.count(len(prow), 1, len(prow) - 1)
            else:
                drec.disposition, drec.reason = "quarantined", "malformed personal-details file"
                state.quarantine.add("players", "malformed_personal_details", {"header": header, "rows": prow}, drec, 1)
                drec.count(max(len(prow), 1), 0, max(len(prow), 1))
        birth, bq, bissue = ids.resolve_birth_date(born, slug)
        if (bissue and bissue != "birth_date_from_filename") or (bissue and drec is not None):
            state.issues.add(
                bissue,
                Severity.INFO if bissue != "birth_date_conflicts_filename" else Severity.WARNING,
                f"birth date quality {bq.value} for {slug}",
                table="players",
                row_key=pid,
                source_path=drec.path if drec else prec.path if prec else None,
            )
        alias = alias_by_slug.get(slug)
        legacy_display = " ".join(x for x in (first, last) if x) or None
        if alias is not None:
            display = alias.source_name
        elif legacy_display:
            display = legacy_display
        else:
            parts = slug.split("_")
            display = " ".join(p.replace("-", " ").title() for p in (parts[1], parts[0])) if len(parts) >= 3 else slug
            state.issues.add(
                "display_name_from_slug",
                Severity.WARNING,
                f"no personal-details name for {slug}; display name derived from slug",
                table="players",
                row_key=pid,
                source_path=prec.path if prec else None,
            )
        dup = dup_by_slug.get(slug)
        urls = sorted(
            {u for u in (evidence.get(prec.path) if prec else None, alias.source_url if alias else None) if u}
            | set(canon_urls.get(slug, []))
        )
        status = IdentityStatus.CANONICAL
        canonical = None
        if dup is not None:
            if dup.canonical_slug in perf_by_slug:
                status, canonical = IdentityStatus.QUARANTINED_DUPLICATE, ids.player_id_for_slug(dup.canonical_slug)
            else:
                state.issues.add(
                    "duplicate_canonical_missing",
                    Severity.ERROR,
                    f"registry duplicate {slug} has no canonical file {dup.canonical_slug}",
                    table="players",
                    row_key=pid,
                )
        rows.append(
            {
                "player_id": pid,
                "legacy_slug": slug,
                "display_name": display,
                "first_name": first,
                "last_name": last,
                "birth_date": birth,
                "birth_date_quality": bq.value,
                "debut_date": ids._parse_ddmmyyyy(debut) if debut else None,
                "height_cm": ids.parse_measure(height),
                "weight_kg": ids.parse_measure(weight),
                "identity_status": status.value,
                "canonical_player_id": canonical,
                "source_urls": json.dumps(urls) if urls else None,
                "details_source_path": drec.path if drec else None,
                "details_source_sha256": drec.sha256 if drec else None,
                **(_src(prec, None) if prec else _src(drec, None) if drec else {}),
            }
        )
        names = {ids.normalize_name(display)}
        if legacy_display:
            names.add(ids.normalize_name(legacy_display))
        if alias is not None:
            aliases.append(
                {
                    "player_id": pid,
                    "alias": alias.source_name,
                    "alias_kind": "source_name",
                    "evidence": "verified multi-part source surname (refresh 2026-09-24)",
                    "source_url": alias.source_url,
                }
            )
            if legacy_display and legacy_display != alias.source_name:
                aliases.append(
                    {
                        "player_id": pid,
                        "alias": legacy_display,
                        "alias_kind": "display_variant",
                        "evidence": "legacy personal-details split of the source surname",
                        "source_url": alias.source_url,
                    }
                )
        if dup is not None and canonical is not None:
            aliases.append(
                {
                    "player_id": canonical,
                    "alias": slug,
                    "alias_kind": "legacy_slug",
                    "evidence": dup.reason,
                    "source_url": dup.source_url,
                }
            )
            if legacy_display:
                aliases.append(
                    {
                        "player_id": canonical,
                        "alias": legacy_display,
                        "alias_kind": "display_variant",
                        "evidence": f"display name on quarantined duplicate {slug}",
                        "source_url": dup.source_url,
                    }
                )
        state.player_names[pid] = names
        state.players[pid] = rows[-1]
    for a in aliases:
        if a["alias_kind"] == "display_variant" and a["player_id"] in state.player_names:
            state.player_names[a["player_id"]].add(ids.normalize_name(a["alias"]))
    # duplicate aliases (same alias text) collapse deterministically
    uniq = {(a["player_id"], a["alias"]): a for a in aliases}
    return rows, [uniq[k] for k in sorted(uniq)]


