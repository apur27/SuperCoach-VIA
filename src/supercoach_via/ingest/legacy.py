def _import_lineups(state: State, records: list[FileRecord]) -> Any:
    """Resolve lineup name tokens to identities; returns an Arrow table (columnar: ~700k rows).

    Pass 1: exact normalized name among the players with a player_games row for that
    match+club (a set of k identical tokens resolves only if exactly k such players).
    Pass 2 (unresolved only): first + last name word unique among that match's
    still-unclaimed participants (multi-part surnames the legacy slug split), then a
    unique club-season name. Anything else is quarantined with candidates.
    """
    import pyarrow as pa

    out: dict[tuple[str, str, str], tuple[Any, ...]] = {}
    acc = Counter[str]()
    for rec in records:
        header, rows = _csv_rows(rec)
        if header != ["year", "date", "round_num", "team_name", "players"]:
            rec.disposition, rec.reason = "quarantined", "unexpected lineup header"
            for i, r in enumerate(rows, start=1):
                state.quarantine.add("lineups", "unexpected_header", {"cells": r, "header": header}, rec, i)
            rec.count(len(rows), 0, len(rows))
            acc["rows_read"] += len(rows)
            acc["rows_quarantined"] += len(rows)
            continue
        imported = quarantined = 0
        for i, cells in enumerate(rows, start=1):
            acc["rows_read"] += 1
            raw = dict(zip(header, cells, strict=False))
            yr = _int(raw.get("year"))
            tokens = [t.strip() for t in (raw.get("players") or "").split(";") if t.strip()]
            club = _club(state, raw.get("team_name", ""), yr, rec) if yr is not None and len(cells) == 5 else None
            match: MatchRef | None = None
            cands: list[MatchRef] = []
            if club is not None and yr is not None:
                stage = season.parse_stage_cached(raw["round_num"])
                cands = state.club_stage_index.get((yr, stage.stage_id, club), [])
                if len(cands) == 1:
                    match = cands[0]
                else:
                    exact = [m for m in cands if m.local_start == raw["date"].strip()]
                    if len(exact) != 1:
                        d = _date(raw["date"].strip())
                        exact = [m for m in cands if m.match_date is not None and m.match_date == d]
                    match = exact[0] if len(exact) == 1 else None
            if match is None or club is None or yr is None:
                state.quarantine.add(
                    "lineups", "lineup_row_unlinked", raw, rec, i, season=yr, candidates=[m.match_id for m in cands]
                )
                quarantined += 1
                acc["rows_quarantined"] += 1
                acc["tokens_read"] += len(tokens)
                acc["tokens_quarantined"] += len(tokens)
                continue
            imported += 1
            acc["rows_linked"] += 1
            by_name = state.match_names.get((match.match_id, club), {})
            season_names = state.club_season_names.get((yr, club), {})
            norm = [ids.normalize_name(t) for t in tokens]
            counts = Counter(norm)
            assigned: list[tuple[str, str] | None] = [None] * len(tokens)
            used_nm: Counter[str] = Counter()
            claimed: set[str] = set()
            for k, nm in enumerate(norm):  # pass 1: exact name within match participation
                pids = by_name.get(nm, [])
                if pids and len(pids) == counts[nm]:
                    pid = sorted(pids)[used_nm[nm]]
                    used_nm[nm] += 1
                    assigned[k] = (pid, "match_participation")
                    claimed.add(pid)
            participants: dict[str, set[tuple[str, str]]] = {}
            for nm, pids in by_name.items():
                fl = _first_last(nm)
                for pid in pids:
                    if fl:
                        participants.setdefault(pid, set()).add(fl)
            for k, nm in enumerate(norm):  # pass 2: fallbacks for unresolved tokens only
                if assigned[k] is not None:
                    continue
                fl = _first_last(nm)
                hits = sorted(p for p, keys in participants.items() if p not in claimed and fl in keys) if fl else []
                if len(hits) == 1 and counts[nm] == 1:
                    assigned[k] = (hits[0], "match_first_last_word")
                    claimed.add(hits[0])
                elif not by_name.get(nm) and len(season_names.get(nm, ())) == 1 and counts[nm] == 1:
                    pid = next(iter(season_names[nm]))
                    if pid not in claimed:
                        assigned[k] = (pid, "club_season")
                        claimed.add(pid)
            for k, t in enumerate(tokens):
                acc["tokens_read"] += 1
                got = assigned[k]
                key = (match.match_id, club, got[0]) if got else None
                if got is None or key is None or key in out:
                    state.quarantine.add(
                        "lineups",
                        "lineup_token_unresolved" if got is None else "lineup_token_duplicate",
                        {"token": t, "row": raw},
                        rec,
                        i,
                        season=yr,
                        candidates={
                            "match": sorted(by_name.get(norm[k], [])),
                            "club_season": sorted(season_names.get(norm[k], ())),
                        },
                        discriminator=f"{t}#{k}",
                    )
                    acc["tokens_quarantined"] += 1
                    continue
                acc["tokens_resolved"] += 1
                acc[f"resolution:{got[1]}"] += 1
                conf = "high" if got[1] == "match_participation" else "medium"
                out[key] = (match.match_id, club, got[0], yr, conf, t, got[1], rec.path, rec.sha256, i)
        rec.count(len(rows), imported, quarantined)
    for key_ in (
        "rows_read",
        "rows_linked",
        "rows_quarantined",
        "tokens_read",
        "tokens_resolved",
        "tokens_quarantined",
    ):
        acc.setdefault(key_, 0)
    acc_d: dict[str, Any] = dict(sorted(acc.items()))
    acc_d["token_resolution_rate"] = (
        round(acc["tokens_resolved"] / acc["tokens_read"], 6) if acc["tokens_read"] else None
    )
    state.accounting["lineups"] = acc_d
    keys = sorted(out)
    cols = {name: [out[k][j] for k in keys] for j, name in enumerate(_LINEUP_COLS)}
    del out
    nrows = len(keys)
    cols.update(
        role=["played"] * nrows,
        announced_at=[None] * nrows,
        provenance=[Provenance.LEGACY_IMPORT.value] * nrows,
    )
    schema = TABLES["lineups"].arrow_schema()
    return pa.Table.from_pydict({f.name: cols[f.name] for f in schema}, schema=schema)


