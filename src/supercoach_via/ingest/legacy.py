def _parse_score(v: Any) -> tuple[int | None, str | None]:
    m = re.fullmatch(r"(\d+)\.(\d+)\.(\d+)", str(v or "").strip())
    if not m:
        return None, f"unparseable score {v!r}"
    g, b, p = (int(x) for x in m.groups())
    if 6 * g + b != p:
        return None, f"score arithmetic mismatch {v!r}"
    return p, None


def _import_live(state: State, recs: Mapping[str, list[FileRecord]]) -> list[dict[str, Any]]:
    out: dict[tuple[str, str], dict[str, Any]] = {}
    for rec in recs.get("live_state", []):
        fname = rec.path.rsplit("/", 1)[-1]
        try:
            payload = json.loads(rec.data)
            header = payload["header"]
            gid = str(payload["gameid"])
        except (ValueError, KeyError, TypeError) as exc:
            state.quarantine.add("live_snapshots", "malformed_payload", {"error": str(exc)}, rec, None)
            rec.disposition, rec.reason = "quarantined", "malformed live snapshot JSON"
            rec.count(1, 0, 1)
            continue
        anomalies: list[str] = []
        hs, ha = _parse_score(header.get("home_score"))
        as_, aa = _parse_score(header.get("away_score"))
        anomalies += [a for a in (ha, aa) if a]
        fetched = None
        try:
            fetched = datetime.fromisoformat(str(payload.get("fetched_at_utc")).replace("Z", "+00:00")).astimezone(UTC)
        except ValueError:
            anomalies.append("unparseable fetched_at_utc")
        yr = _int(str((payload.get("meta") or {}).get("year") or "")) or (fetched.year if fetched else None)
        home_name, away_name = header.get("home_team_full"), header.get("away_team_full")
        match_id = None
        if yr and home_name and away_name and fetched:
            h = state.clubs.resolve(home_name, yr)
            a = state.clubs.resolve(away_name, yr)
            d0 = fetched.date()
            cands = [
                m
                for m in state.matches.values()
                if m.season == yr
                and {m.home, m.away} == {h, a}
                and m.match_date is not None
                and abs((m.match_date - d0).days) <= 1
            ]
            if len(cands) == 1:
                match_id = cands[0].match_id
            else:
                anomalies.append(f"match mapping ambiguous/absent ({len(cands)} candidates)")
        phase = re.sub(r"^\d+_\d{8}_\d{4}_", "", fname[:-5])
        payload_hash = rec.sha256
        out[(gid, payload_hash)] = {
            "source_game_id": gid,
            "payload_hash": payload_hash,
            "match_id": match_id,
            "fetched_at": fetched,
            "status": header.get("status"),
            "quarter": phase,
            "home_score": hs,
            "away_score": as_,
            "schema_version": 1,
            "anomalies": json.dumps(sorted(anomalies)) if anomalies else None,
            "payload_kind": "state_json",
            "home_source_name": home_name,
            "away_source_name": away_name,
            "source_round_label": header.get("round"),
            **_src(rec, None),
        }
        rec.count(1, 1, 0)
    for rec in recs.get("live_players", []):
        fname = rec.path.rsplit("/", 1)[-1]
        gid = fname.split("_", 1)[0]
        out[(gid, rec.sha256)] = {
            "source_game_id": gid,
            "payload_hash": rec.sha256,
            "match_id": None,
            "fetched_at": None,
            "status": None,
            "quarter": None,
            "home_score": None,
            "away_score": None,
            "schema_version": 1,
            "anomalies": json.dumps(
                ["per-player FanFooty payload: colNN_unknown and misindexed goals/behinds/clangers are not facts"]
            ),
            "payload_kind": "players_csv",
            "home_source_name": None,
            "away_source_name": None,
            "source_round_label": None,
            **_src(rec, None),
        }
        rec.count(1, 1, 0)
        rec.reason = "payload archived by hash; per-player cells not imported as facts"
    return [out[k] for k in sorted(out)]


