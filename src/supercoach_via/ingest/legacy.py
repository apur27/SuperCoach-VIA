_SCORE_TOKEN = re.compile(r"^\d+\.\d+\.\d+$")
OpponentEvidence = Callable[[int, str, str], str | None]


def opponent_evidence(perf: list[FileRecord]) -> OpponentEvidence:
    """Lookup (season, stage_id, team name) -> the opponent name iff player rows agree both ways.

    Unanimous means: every row of ``team`` in that season/stage names the same opponent X,
    and every row of X in that season/stage names ``team``. Used only to recover the club
    of a malformed legacy match row (never scores). Scans raw bytes; called rarely.
    """
    ncells = len(LEGACY_PLAYER_HEADER)

    def opponents(season_: int, stage_id: str, team: str) -> list[str]:
        needle = f"\n{team},{season_},".encode()
        found: list[str] = []
        for rec in perf:
            data = rec.data
            start = data.find(needle)
            while start != -1:
                end = data.find(b"\n", start + 1)
                cells = data[start + 1 : end if end != -1 else None].decode("utf-8").rstrip("\r").split(",")
                if len(cells) == ncells and season.parse_stage_cached(cells[4]).stage_id == stage_id:
                    found.append(cells[3])
                start = data.find(needle, start + 1)
        return found

    def lookup(season_: int, stage_id: str, team: str) -> str | None:
        forward = set(opponents(season_, stage_id, team))
        if len(forward) != 1:
            return None
        opp = next(iter(forward))
        back = set(opponents(season_, stage_id, opp))
        return opp if back == {team} else None

    return lookup


def _import_matches(
    state: State, records: list[FileRecord], evidence: OpponentEvidence | None = None
) -> list[dict[str, Any]]:
    staged: list[dict[str, Any]] = []
    for rec in records:
        header, rows = _csv_rows(rec)
        if tuple(header) != MATCH_HEADER:
            rec.disposition, rec.reason = "quarantined", "unexpected match header"
            for i, r in enumerate(rows, start=1):
                state.quarantine.add("matches", "unexpected_header", {"cells": r, "header": header}, rec, i)
            rec.count(len(rows), 0, len(rows))
            continue
        imported = quarantined = 0
        for i, cells in enumerate(rows, start=1):
            raw: dict[str, Any] = dict(zip(MATCH_HEADER, cells, strict=False))
            yr = _int(raw.get("year"))
            reason = None
            if len(cells) != len(MATCH_HEADER):
                reason, raw = "malformed_column_count", {"cells": cells}
            elif yr is None:
                reason = "malformed_value"
            score_cells = [raw[f"team_{t}_{q}_{k}"] for t in (1, 2) for q in _QUARTERS for k in ("goals", "behinds")]
            if reason is None and any(c.strip() and _int(c) is None for c in score_cells):
                reason = "malformed_value"
            home = away = None
            malformed_opp: str | None = None
            if reason is None and yr is not None:
                home = _club(state, raw["team_1_team_name"], yr, rec)
                if _SCORE_TOKEN.match(raw["team_2_team_name"].strip()) and evidence is not None and home:
                    # extra-time final: legacy scraper wrote a score into team_2's name cell
                    malformed_opp = evidence(yr, season.parse_stage(raw["round_num"]).stage_id, raw["team_1_team_name"])
                    away = _club(state, malformed_opp, yr, rec) if malformed_opp else None
                else:
                    away = _club(state, raw["team_2_team_name"], yr, rec)
                if home is None or away is None or home == away:
                    reason = "unresolved_club"
                    malformed_opp = None
            if reason is not None or yr is None or home is None or away is None:
                state.quarantine.add("matches", reason or "malformed_value", raw, rec, i, season=yr)
                state.issues.add(
                    f"match_{reason}",
                    Severity.ERROR,
                    f"match row quarantined: {reason}",
                    table="matches",
                    row_key=f"{rec.path}:{i}",
                    source_path=rec.path,
                    season=yr,
                    remediation="repair from source (refresh --repair-season)",
                )
                quarantined += 1
                continue
            stage = season.parse_stage(raw["round_num"])
            if not stage.recognized:
                state.issues.add(
                    "stage_unrecognized",
                    Severity.ERROR,
                    f"unrecognized stage token {stage.label!r} preserved as {stage.stage_id} (stage_type=other)",
                    table="matches",
                    row_key=f"{rec.path}:{i}",
                    source_path=rec.path,
                    season=yr,
                    remediation="map the token in domain.season before time-sensitive use",
                )
            dt_raw = raw["date"].strip()
            local_start: str | None = None
            match_date = _date(dt_raw)
            if match_date is not None and re.fullmatch(r"\d{4}-\d{2}-\d{2} \d{2}:\d{2}", dt_raw):
                local_start, precision = dt_raw, DatePrecision.MINUTE
            elif match_date is not None:
                precision = DatePrecision.DAY
            else:
                precision = DatePrecision.UNKNOWN
                state.issues.add(
                    "match_date_unparseable",
                    Severity.WARNING,
                    f"match date {dt_raw!r} unparseable",
                    table="matches",
                    row_key=f"{rec.path}:{i}",
                    source_path=rec.path,
                    season=yr,
                )
            if match_date is not None and match_date.year != yr:
                state.issues.add(
                    "match_date_outside_season",
                    Severity.WARNING,
                    f"match date {match_date} outside season {yr}",
                    table="matches",
                    row_key=f"{rec.path}:{i}",
                    source_path=rec.path,
                    season=yr,
                )
            scores = {
                f"{side}_{q}_{k}": None if malformed_opp else _int(raw[f"team_{t}_{q}_{k}"])
                for t, side in ((1, "home"), (2, "away"))
                for q in _QUARTERS
                for k in ("goals", "behinds")
            }
            if malformed_opp:
                state.quarantine.add("matches", "source_row_malformed_evidence", raw, rec, i, season=yr)
            att = raw["attendance"].strip()
            attendance = _int(att) if att not in ("", "N/A") else None
            staged.append(
                {
                    "season": yr,
                    "stage": stage,
                    "home": home,
                    "away": away,
                    "home_source_name": raw["team_1_team_name"],
                    "away_source_name": malformed_opp or raw["team_2_team_name"],
                    "malformed_raw": dict(raw) if malformed_opp else None,
                    "venue_source_name": raw["venue"] or None,
                    "local_start": local_start,
                    "match_date": match_date,
                    "precision": precision,
                    "attendance": attendance,
                    "scores": scores,
                    "rec": rec,
                    "row": i,
                    "tiebreak": len(staged),
                }
            )
            imported += 1
        rec.count(len(rows), imported, quarantined)
        if quarantined and not imported:
            rec.disposition = "quarantined"

    # completion status: all score cells present -> complete; all blank -> fixture
    completed_dates = [
        s["match_date"]
        for s in staged
        if s["match_date"] is not None
        and all(s["scores"][f"{side}_final_{k}"] is not None for side in ("home", "away") for k in ("goals", "behinds"))
    ]
    latest_complete = max(completed_dates) if completed_dates else None

    by_season: dict[int, list[dict[str, Any]]] = defaultdict(list)
    for s in staged:
        by_season[s["season"]].append(s)
    out: list[dict[str, Any]] = []
    observed_venues: dict[str, set[str]] = defaultdict(set)
    for yr in sorted(by_season):
        group = by_season[yr]
        occ = season.replay_occurrences(
            [(s["stage"].stage_id, s["home"], s["away"], s["match_date"]) for s in group],
            [s["tiebreak"] for s in group],
        )
        stage_dates: dict[str, list[date | None]] = defaultdict(list)
        for s in group:
            stage_dates[s["stage"].stage_id].append(s["match_date"])
        orders = season.stage_orders(stage_dates)
        for s, o in zip(group, occ, strict=True):
            stage = s["stage"]
            rec = s["rec"]
            mid = season.make_match_id(yr, stage.stage_id, s["home"], s["away"], o)
            sc = s["scores"]
            finals_present = all(
                sc[f"{side}_final_{k}"] is not None for side in ("home", "away") for k in ("goals", "behinds")
            )
            any_present = any(v is not None for v in sc.values())
            if s["malformed_raw"] is not None:
                status = MatchStatus.UNKNOWN
                state.issues.add(
                    "source_row_malformed",
                    Severity.ERROR,
                    "legacy row has a score in team_2_team_name (extra-time final); team 2 cells are "
                    f"shifted so ALL scores are null; away club {s['away']!r} taken from unanimous two-way "
                    "player-row opponent evidence; raw row: "
                    + json.dumps(s["malformed_raw"], ensure_ascii=False, sort_keys=True),
                    table="matches",
                    row_key=mid,
                    source_path=rec.path,
                    season=yr,
                    remediation="re-fetch the match from source (refresh --repair-season)",
                )
            elif finals_present:
                status = MatchStatus.COMPLETE
            elif (
                not any_present
                and s["match_date"] is not None
                and latest_complete is not None
                and s["match_date"] > latest_complete
            ):
                status = MatchStatus.SCHEDULED
            else:
                status = MatchStatus.UNKNOWN
                state.issues.add(
                    "match_scores_missing" if not any_present else "match_scores_partial",
                    Severity.WARNING if not any_present else Severity.ERROR,
                    "match has no scores and is not later than the latest completed match"
                    if not any_present
                    else "match has partial scores; status unknown",
                    table="matches",
                    row_key=mid,
                    source_path=rec.path,
                    season=yr,
                )
            if o > 0:
                prev = next(
                    x
                    for x, xo in zip(group, occ, strict=True)
                    if xo == o - 1
                    and x["stage"].stage_id == stage.stage_id
                    and {x["home"], x["away"]} == {s["home"], s["away"]}
                )
                ps = prev["scores"]
                drawn = (
                    ps["home_final_goals"] is not None
                    and ps["away_final_goals"] is not None
                    and 6 * ps["home_final_goals"] + (ps["home_final_behinds"] or 0)
                    == 6 * ps["away_final_goals"] + (ps["away_final_behinds"] or 0)
                )
                state.issues.add(
                    "replay_after_draw" if drawn else "repeat_meeting_same_stage",
                    Severity.INFO,
                    f"occurrence {o} of {stage.stage_id} between {s['home']} and {s['away']}"
                    + (" follows a drawn match (replay)" if drawn else " without a preceding draw"),
                    table="matches",
                    row_key=mid,
                    source_path=rec.path,
                    season=yr,
                )
            venue_id = state.venues.resolve(s["venue_source_name"]) if s["venue_source_name"] else None
            if s["venue_source_name"] and venue_id is None:
                state.issues.add(
                    "venue_unmapped",
                    Severity.WARNING,
                    f"venue {s['venue_source_name']!r} absent from venue_aliases.csv",
                    table="matches",
                    row_key=mid,
                    source_path=rec.path,
                    season=yr,
                )
            if venue_id is not None:
                observed_venues[venue_id].add(s["venue_source_name"])

            def pts(side: str, _sc: dict[str, int | None] = sc) -> int | None:
                g, b = _sc[f"{side}_final_goals"], _sc[f"{side}_final_behinds"]
                return None if g is None or b is None else 6 * g + b

            row = {
                "match_id": mid,
                "season": yr,
                "stage_label": stage.label,
                "stage_type": stage.stage_type.value,
                "round_number": stage.round_number,
                "stage_order": orders[stage.stage_id],
                "stage_id": stage.stage_id,
                "replay_occurrence": o,
                "home_club_id": s["home"],
                "away_club_id": s["away"],
                "home_source_name": s["home_source_name"],
                "away_source_name": s["away_source_name"],
                "venue_id": venue_id,
                "venue_source_name": s["venue_source_name"],
                "local_start": s["local_start"],
                "match_date": s["match_date"],
                "date_precision": s["precision"].value,
                "status": status.value,
                "attendance": s["attendance"],
                **sc,
                "home_score": pts("home"),
                "away_score": pts("away"),
                **_src(rec, s["row"]),
            }
            out.append(row)
            ref = MatchRef(mid, yr, stage.stage_id, s["home"], s["away"], s["match_date"], s["local_start"], o)
            state.matches[mid] = ref
            state.link_index.setdefault((yr, stage.stage_id, s["home"], s["away"]), []).append(ref)
            state.link_index.setdefault((yr, stage.stage_id, s["away"], s["home"]), []).append(ref)
            state.club_stage_index.setdefault((yr, stage.stage_id, s["home"]), []).append(ref)
            state.club_stage_index.setdefault((yr, stage.stage_id, s["away"]), []).append(ref)
    for lst in (*state.link_index.values(), *state.club_stage_index.values()):
        lst.sort(key=lambda m: (m.occurrence, m.match_id))
    state.accounting["venues_observed"] = {k: sorted(v) for k, v in observed_venues.items()}
    return out


