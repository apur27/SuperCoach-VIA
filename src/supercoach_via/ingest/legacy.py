_INT_RE = r"^\d+(\.0+)?$"
_FLOAT_RE = r"^\d+(\.\d+)?$"


def _import_player_games(state: State, perf: list[FileRecord]) -> Any:
    import pyarrow as pa
    import pyarrow.compute as pc
    import pyarrow.csv as pacsv

    header_line = ",".join(LEGACY_PLAYER_HEADER)
    ncomma = len(LEGACY_PLAYER_HEADER) - 1
    lines: list[str] = []
    raw_lines: list[str] = []
    line_meta: list[tuple[int, int]] = []  # (file index, source row)
    acc_read: Counter[int | None] = Counter()
    acc_imp: Counter[int | None] = Counter()
    acc_q: Counter[int | None] = Counter()
    per_file = [[0, 0, 0] for _ in perf]  # read, imported, quarantined
    dup_slugs = {d.duplicate_slug for d in ids.KNOWN_DUPLICATES}

    def season_of(cells: list[str]) -> int | None:
        return _int(cells[1]) if len(cells) > 1 else None

    for fi, rec in enumerate(perf):
        text = rec.data.decode("utf-8-sig")
        flines = text.split("\n")
        header = flines[0].rstrip("\r") if flines else ""
        body = [ln.rstrip("\r") for ln in flines[1:]]
        if header != header_line:
            rec.disposition, rec.reason = "quarantined", "unexpected performance header"
            for i, ln in enumerate((b for b in body if b), start=1):
                state.quarantine.add("player_games", "unexpected_header", {"line": ln, "header": header}, rec, i)
                per_file[fi][0] += 1
                per_file[fi][2] += 1
                acc_read[None] += 1
                acc_q[None] += 1
            continue
        row_no = 0
        for ln in body:
            if not ln:
                continue
            row_no += 1
            per_file[fi][0] += 1
            if ln.count(",") != ncomma or '"' in ln:
                cells = ln.split(",")
                sn = season_of(cells)
                state.quarantine.add("player_games", "malformed_column_count", {"line": ln}, rec, row_no, season=sn)
                per_file[fi][2] += 1
                acc_read[sn] += 1
                acc_q[sn] += 1
                continue
            lines.append(f"{fi},{row_no},{ln}")
            raw_lines.append(ln)
            line_meta.append((fi, row_no))

    names = ["fidx", "srow", *LEGACY_PLAYER_HEADER]
    blob = "\n".join(lines).encode()
    del lines
    if blob:
        table = pacsv.read_csv(
            io.BytesIO(blob),
            read_options=pacsv.ReadOptions(column_names=names, use_threads=True, block_size=1 << 24),
            parse_options=pacsv.ParseOptions(quote_char=False, escape_char=False, newlines_in_values=False),
            convert_options=pacsv.ConvertOptions(
                column_types={n: (pa.int32() if n in ("fidx", "srow") else pa.string()) for n in names},
                strings_can_be_null=False,
                quoted_strings_can_be_null=False,
            ),
        )
    else:
        table = pa.table({n: pa.array([], pa.int32() if n in ("fidx", "srow") else pa.string()) for n in names})
    del blob
    n = table.num_rows
    empty = pa.scalar(None, pa.string())

    def blank_to_null(col: Any) -> Any:
        return pc.if_else(pc.equal(col, ""), empty, col)

    bad = pa.array([False] * n)
    typed: dict[str, Any] = {}
    for legacy_name in _LEGACY_STATS:
        col = table[legacy_name]
        canon = _CANON_OF_LEGACY[legacy_name]
        pattern = _FLOAT_RE if canon == "time_on_ground_pct" else _INT_RE
        ok = pc.or_(pc.equal(col, ""), pc.match_substring_regex(col, pattern))
        bad = pc.or_(bad, pc.invert(ok))
        clean = pc.if_else(ok, blank_to_null(col), empty)
        if canon == "time_on_ground_pct":
            typed[canon] = pc.cast(clean, pa.float64())
        else:
            typed[canon] = pc.cast(pc.replace_substring_regex(clean, r"\.0+$", ""), pa.int32())
    year_ok = pc.match_substring_regex(table["year"], r"^\d{4}$")
    bad = pc.or_(bad, pc.invert(year_ok))
    gp = table["games_played"]
    gp_ok = pc.or_(pc.equal(gp, ""), pc.match_substring_regex(gp, r"^\d+[↑↓]?$"))
    bad = pc.or_(bad, pc.invert(gp_ok))
    counter_str = pc.replace_substring_regex(pc.if_else(gp_ok, blank_to_null(gp), empty), r"[↑↓]$", "")
    counter = pc.cast(counter_str, pa.int32())
    jersey = table["jersey_num"]
    jersey_ok = pc.or_(pc.equal(jersey, ""), pc.match_substring_regex(jersey, _INT_RE))
    bad = pc.or_(bad, pc.invert(jersey_ok))
    jersey_int = pc.cast(
        pc.replace_substring_regex(pc.if_else(jersey_ok, blank_to_null(jersey), empty), r"\.0+$", ""), pa.int32()
    )
    date_str = table["date"]
    date_ok = pc.match_substring_regex(date_str, r"^\d{4}-\d{2}-\d{2}$")
    row_dates = pc.cast(
        pc.strptime(pc.if_else(date_ok, date_str, empty), format="%Y-%m-%d", unit="s", error_is_null=True),
        pa.date32(),
    )

    bad_l: list[bool] = bad.to_pylist()
    year_l: list[int | None] = [
        int(y) if ok else None for y, ok in zip(table["year"].to_pylist(), year_ok.to_pylist(), strict=True)
    ]
    team_l: list[str] = table["team"].to_pylist()
    opp_l: list[str] = table["opponent"].to_pylist()
    round_l: list[str] = table["round"].to_pylist()
    date_l: list[date | None] = row_dates.to_pylist()

    slugs = [ids.slug_from_filename(r.path.rsplit("/", 1)[-1]) for r in perf]
    pids = [ids.player_id_for_slug(s) for s in slugs]
    # link
    match_l: list[str | None] = [None] * n
    club_l: list[str | None] = [None] * n
    oppid_l: list[str | None] = [None] * n
    stage_l: list[str] = [""] * n
    method_l: list[str] = [""] * n
    dq_l: list[str] = [""] * n
    reason_l: list[str | None] = [None] * n
    cand_l: dict[int, Any] = {}
    seen_key_count: Counter[tuple[int, int, str, str, str]] = Counter()
    fidx_l = [m[0] for m in line_meta]
    srow_l = [m[1] for m in line_meta]
    for i in range(n):
        fi = fidx_l[i]
        yr = year_l[i]
        if bad_l[i] or yr is None:
            reason_l[i] = "malformed_value"
            continue
        rec = perf[fi]
        club = _club(state, team_l[i], yr, rec)
        opp = _club(state, opp_l[i], yr, rec)
        if club is None or opp is None:
            reason_l[i] = "unresolved_club"
            cand_l[i] = {"team": team_l[i], "opponent": opp_l[i]}
            continue
        club_l[i], oppid_l[i] = club, opp
        stage = season.parse_stage_cached(round_l[i])
        stage_l[i] = stage.stage_id
        cands = state.link_index.get((yr, stage.stage_id, club, opp))
        if not cands:
            reason_l[i] = "unlinked_no_match"
            cand_l[i] = sorted(
                m.match_id
                for k, v in state.link_index.items()
                if k[0] == yr and k[2] == club and k[3] == opp
                for m in v
            )
            continue
        key = (fi, yr, stage.stage_id, club, opp)
        k = seen_key_count[key]
        seen_key_count[key] += 1
        chosen: MatchRef | None = None
        if len(cands) == 1:
            chosen, method = cands[0], "key"
        else:
            same_day = [m for m in cands if m.match_date is not None and m.match_date == date_l[i]]
            if len(same_day) == 1:
                chosen, method = same_day[0], "date_tiebreak"
            elif k < len(cands):
                chosen, method = cands[k], "row_order"
            else:
                method = ""
        if chosen is None:
            reason_l[i] = "ambiguous_match"
            cand_l[i] = [m.match_id for m in cands]
            continue
        match_l[i] = chosen.match_id
        method_l[i] = method
        dq_l[i] = season.row_date_quality(date_l[i], chosen.match_date, yr).value

    # dedupe (match, player, club): keep fixture-verified first, then earliest row
    groups: dict[tuple[str, str, str], list[int]] = defaultdict(list)
    for i in range(n):
        if reason_l[i] is None and match_l[i] is not None and club_l[i] is not None:
            groups[(match_l[i], pids[fidx_l[i]], club_l[i])].append(i)  # type: ignore[index]
    keep = [False] * n
    for members in groups.values():
        members.sort(key=lambda j: (dq_l[j] != DateQuality.FIXTURE_VERIFIED.value, srow_l[j]))
        keep[members[0]] = True
        for j in members[1:]:
            reason_l[j] = "duplicate_player_game"
            cand_l[j] = {"kept_source_row": srow_l[members[0]], "match_id": match_l[j]}

    # duplicate identities: quarantine, compare with canonical rows
    canon_rows: dict[tuple[str, str], int] = {}
    for i in range(n):
        if keep[i]:
            canon_rows[(pids[fidx_l[i]], match_l[i])] = i  # type: ignore[index]
    dup_canon = {
        ids.player_id_for_slug(d.duplicate_slug): ids.player_id_for_slug(d.canonical_slug) for d in ids.KNOWN_DUPLICATES
    }
    compare_cols = [c for c in LEGACY_PLAYER_HEADER if c not in ("date",)]
    for i in range(n):
        slug = slugs[fidx_l[i]]
        if (
            slug not in dup_slugs
            or state.players.get(pids[fidx_l[i]], {}).get("identity_status")
            != IdentityStatus.QUARANTINED_DUPLICATE.value
        ):
            continue
        canonical_pid = dup_canon[pids[fidx_l[i]]]
        mid = match_l[i]
        was_kept = keep[i]
        keep[i] = False
        reason_l[i] = "duplicate_identity"
        cand_l[i] = {"canonical_player_id": canonical_pid, "match_id": mid}
        cj = canon_rows.get((canonical_pid, mid)) if mid else None
        rec = perf[fidx_l[i]]
        if cj is None:
            state.issues.add(
                "duplicate_identity_unmatched_row",
                Severity.WARNING,
                f"duplicate-identity row {slug}:{srow_l[i]} has no canonical row for match {mid}",
                table="player_games",
                row_key=f"{pids[fidx_l[i]]}|{mid}",
                source_path=rec.path,
                season=year_l[i],
            )
            continue
        a = dict(zip(LEGACY_PLAYER_HEADER, raw_lines[i].split(","), strict=True))
        b = dict(zip(LEGACY_PLAYER_HEADER, raw_lines[cj].split(","), strict=True))
        diffs = {c: (a[c], b[c]) for c in compare_cols if _norm_cell(a[c]) != _norm_cell(b[c])}
        if diffs:
            state.issues.add(
                "duplicate_identity_cell_diff",
                Severity.WARNING,
                "duplicate vs canonical differing cells (duplicate, canonical): "
                + json.dumps(diffs, ensure_ascii=False, sort_keys=True),
                table="player_games",
                row_key=f"{canonical_pid}|{mid}",
                source_path=rec.path,
                season=year_l[i],
                remediation="canonical row retained; duplicate cells preserved in quarantine",
            )
        _ = was_kept

    # quarantine + accounting
    for i in range(n):
        fi = fidx_l[i]
        yr = year_l[i]
        acc_read[yr] += 1
        if keep[i]:
            acc_imp[yr] += 1
            per_file[fi][1] += 1
            continue
        acc_q[yr] += 1
        per_file[fi][2] += 1
        reason = reason_l[i] or "unlinked_no_match"
        state.quarantine.add(
            "player_games",
            reason,
            dict(zip(LEGACY_PLAYER_HEADER, raw_lines[i].split(","), strict=True)),
            perf[fi],
            srow_l[i],
            season=yr,
            candidates=cand_l.get(i),
        )
    for fi, rec in enumerate(perf):
        r, imp, q = per_file[fi]
        rec.count(r, imp, q)
        if slugs[fi] in dup_slugs and imp == 0 and r:
            rec.disposition, rec.reason = "quarantined", "duplicate legacy identity (see DATA_REFRESH.md)"

    # aggregated issues (row-level would be noise): row-order links, inferred/source dates
    agg: Counter[tuple[str, int]] = Counter()
    for i in range(n):
        if keep[i]:
            if method_l[i] == "row_order":
                agg[("player_game_linked_by_row_order", year_l[i] or 0)] += 1
            if dq_l[i] != DateQuality.FIXTURE_VERIFIED.value:
                agg[(f"player_date_{dq_l[i]}", year_l[i] or 0)] += 1
    for (rule, yr), cnt in sorted(agg.items()):
        state.issues.add(
            rule,
            Severity.INFO,
            f"{cnt} imported player-game rows in {yr}: {rule.replace('_', ' ')}",
            table="player_games",
            row_key=f"season:{yr}",
            season=yr,
        )
    for (q_reason, yr), cnt in sorted(
        Counter((reason_l[i], year_l[i]) for i in range(n) if not keep[i]).items(), key=str
    ):
        state.issues.add(
            f"player_game_quarantined_{q_reason}",
            Severity.INFO if q_reason == "duplicate_identity" else Severity.WARNING,
            f"{cnt} player-game rows quarantined in {yr}: {q_reason}",
            table="player_games",
            row_key=f"season:{yr}",
            season=yr,
        )

    # build canonical table
    idx = pa.array([i for i in range(n) if keep[i]], pa.int64())
    kept_i = idx.to_pylist()
    rev = [f"rev:{hashlib.sha256(raw_lines[i].encode()).hexdigest()[:32]}" for i in kept_i]
    cols: dict[str, Any] = {
        "match_id": pa.array([match_l[i] for i in kept_i], pa.string()),
        "player_id": pa.array([pids[fidx_l[i]] for i in kept_i], pa.string()),
        "club_id": pa.array([club_l[i] for i in kept_i], pa.string()),
        "season": pa.array([year_l[i] for i in kept_i], pa.int32()),
        "opponent_club_id": pa.array([oppid_l[i] for i in kept_i], pa.string()),
        "stage_label": pc.take(table["round"], idx),
        "stage_id": pa.array([stage_l[i] for i in kept_i], pa.string()),
        "club_source_name": pc.take(table["team"], idx),
        "opponent_source_name": pc.take(table["opponent"], idx),
        "link_method": pa.array([method_l[i] for i in kept_i], pa.string()),
        "match_date": pc.take(row_dates, idx),
        "date_quality": pa.array([dq_l[i] for i in kept_i], pa.string()),
        "career_game_counter": pc.take(counter, idx),
        "career_game_counter_token": pc.take(blank_to_null(gp), idx),
        "result": pc.take(blank_to_null(table["result"]), idx),
        "jersey_number": pc.take(jersey_int, idx),
        **{c: pc.take(typed[c], idx) for c in PLAYER_STAT_COLUMNS},
        "available_at": pa.nulls(len(kept_i), pa.timestamp("us", tz="UTC")),
        "revision_id": pa.array(rev, pa.string()),
        "provenance": pa.array([Provenance.LEGACY_IMPORT.value] * len(kept_i), pa.string()),
        "source_path": pa.array([perf[fidx_l[i]].path for i in kept_i], pa.string()),
        "source_sha256": pa.array([perf[fidx_l[i]].sha256 for i in kept_i], pa.string()),
        "source_row": pa.array([srow_l[i] for i in kept_i], pa.int64()),
    }
    schema = TABLES["player_games"].arrow_schema()
    out = pa.table([cols[f.name].cast(f.type) for f in schema], schema=schema)

    # name indexes for lineups / predictions / drafts
    for i in kept_i:
        pid = pids[fidx_l[i]]
        yr = year_l[i]
        club = club_l[i]
        mid = match_l[i]
        assert yr is not None and club is not None and mid is not None
        for nm in state.player_names.get(pid, ()):
            state.match_names.setdefault((mid, club), {}).setdefault(nm, [])
            if pid not in state.match_names[(mid, club)][nm]:
                state.match_names[(mid, club)][nm].append(pid)
            state.club_season_names.setdefault((yr, club), {}).setdefault(nm, set()).add(pid)
        state.season_players.setdefault(yr, set()).add(pid)
        if yr < state.first_season.get(pid, 10_000):
            state.first_season[pid] = yr
    state.accounting["player_games"] = {
        "read": sum(acc_read.values()),
        "imported": sum(acc_imp.values()),
        "quarantined": sum(acc_q.values()),
        "by_season": {
            str(k): {"read": acc_read[k], "imported": acc_imp[k], "quarantined": acc_q[k]}
            for k in sorted(acc_read, key=lambda x: (x is None, x or 0))
        },
        "link_methods": dict(sorted(Counter(method_l[i] for i in kept_i).items())),
        "date_quality": dict(sorted(Counter(dq_l[i] for i in kept_i).items())),
    }
    return out


