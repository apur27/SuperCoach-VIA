"""Legacy CSV corpus -> immutable, coverage-aware canonical snapshot.

``import_legacy`` reads every file under ``<source_root>/data`` (plus the root biography
export), accounts for each one as imported / ignored-with-reason / quarantined, maps the
legacy columns to canonical tables (``domain.schemas.TABLES``) and writes a content-hashed
snapshot through ``SnapshotBuilder``. Nothing is silently dropped: every legacy row is
either imported or quarantined with its original cells and a reason. Imported legacy data
is always ``DatasetStatus.LEGACY_UNVERIFIED``.

Determinism: tables are sorted by key, IDs are content/identity derived and no wall-clock
value enters any row, so identical inputs give the identical snapshot ID.
"""

