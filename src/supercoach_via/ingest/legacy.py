def _h(*parts: object, n: int = 24) -> str:
    return hashlib.sha256("\x1f".join(str(p) for p in parts).encode()).hexdigest()[:n]


def classify(rel: str) -> str:
    """Map a repo-relative path to its legacy file family."""
    name = rel.rsplit("/", 1)[-1]
    if rel == ROOT_BIOS:
        return "top100_bios"
    if name == ".gitkeep":
        return "placeholder"
    if rel == EVIDENCE_REL:
        return "identity_evidence"
    if re.fullmatch(r"data/matches/matches_\d{4}\.csv", rel):
        return "matches"
    if rel.startswith("data/player_data/") and rel.count("/") == 2:
        if name.endswith(ids.PERFORMANCE_SUFFIX):
            return "player_performance"
        if name.endswith(ids.PERSONAL_SUFFIX):
            return "player_personal"
    if re.fullmatch(r"data/lineups/team_lineups_[a-z_]+\.csv", rel):
        return "lineups"
    fixed = {
        "data/drafts/afl_draft_history.csv": "drafts_national",
        "data/drafts/afl_rookie_draft_history.csv": "drafts_rookie",
        "data/drafts/draftguru_enrichment.csv": "drafts_draftguru",
        "data/drafts/afl_draft_schools.csv": "draft_schools",
        "data/top100/all_time_top_100.csv": "rank_scores",
        "data/player_status.csv": "player_status",
        "data/prediction/optuna_best_params.json": "model_cache",
    }
    if rel in fixed:
        return fixed[rel]
    if re.fullmatch(r"data/contracts/[^/]+\.csv", rel):
        return "contracts"
    if re.fullmatch(r"data/conceded_stats/[^/]+\.csv", rel):
        return "conceded_stats"
    if re.fullmatch(r"data/live_snapshots/[^/]+\.json", rel):
        return "live_state"
    if re.fullmatch(r"data/live_snapshots/[^/]+_players\.csv", rel):
        return "live_players"
    if rel.startswith("data/prediction/backtest/"):
        return "legacy_backtest"
    if re.fullmatch(r"data/prediction/(oldModelData/)?(next_[a-z0-9_]+|prediction_vs_actual_[a-z0-9_]+)\.csv", rel):
        return "legacy_predictions"
    if re.fullmatch(r"data/top100/yearly/year_\d{4}\.csv", rel):
        return "rank_yearly"
    if re.fullmatch(r"data/era_[a-z_]+\.(csv|json)", rel):
        return "era_outputs"
    return "unknown"


@dataclass
class FileRecord:
    path: str
    family: str
    bytes: int
    sha256: str
    data: builtins.bytes
    disposition: str = "imported"
    reason: str | None = None
    rows_read: int | None = None
    rows_imported: int | None = None
    rows_quarantined: int | None = None

    def count(self, read: int, imported: int, quarantined: int) -> None:
        self.rows_read = (self.rows_read or 0) + read
        self.rows_imported = (self.rows_imported or 0) + imported
        self.rows_quarantined = (self.rows_quarantined or 0) + quarantined

    def as_report(self) -> dict[str, Any]:
        return {
            "path": self.path,
            "family": self.family,
            "bytes": self.bytes,
            "sha256": self.sha256,
            "disposition": self.disposition,
            "reason": self.reason,
            "rows_read": self.rows_read,
            "rows_imported": self.rows_imported,
            "rows_quarantined": self.rows_quarantined,
        }


def _read_file(path: Path, rel: str) -> FileRecord:
    data = path.read_bytes()
    return FileRecord(rel, classify(rel), len(data), hashlib.sha256(data).hexdigest(), data)


def _inventory(source_root: Path) -> list[FileRecord]:
    data_dir = source_root / "data"
    if not data_dir.is_dir():
        raise LegacyImportError(f"no data/ directory under {source_root}")
    targets: list[tuple[Path, str]] = []
    for dirpath, dirnames, filenames in os.walk(data_dir):
        dirnames.sort()
        for fn in sorted(filenames):
            p = Path(dirpath) / fn
            targets.append((p, p.relative_to(source_root).as_posix()))
    for extra in (ROOT_BIOS, EVIDENCE_REL):
        if (source_root / extra).is_file():
            targets.append((source_root / extra, extra))
    with ThreadPoolExecutor(max_workers=8) as pool:
        records = list(pool.map(lambda t: _read_file(*t), targets))
    return sorted(records, key=lambda r: r.path)


class IssueSink:
    """Collects quality_issues rows with deterministic IDs."""

    def __init__(self) -> None:
        self.rows: dict[str, dict[str, Any]] = {}

    def add(
        self,
        rule_id: str,
        severity: Severity,
        explanation: str,
        *,
        table: str | None = None,
        row_key: str | None = None,
        source_path: str | None = None,
        season: int | None = None,
        remediation: str | None = None,
        status: str = "open",
        acceptance_basis: str | None = None,
    ) -> None:
        issue_id = f"qi:{_h(rule_id, table, row_key, source_path, explanation)}"
        self.rows[issue_id] = {
            "issue_id": issue_id,
            "severity": severity.value,
            "status": status,
            "table_name": table,
            "row_key": row_key,
            "source_path": source_path,
            "rule_id": rule_id,
            "explanation": explanation,
            "remediation": remediation,
            "acceptance_basis": acceptance_basis,
            "season": season,
        }


class Quarantine:
    def __init__(self) -> None:
        self.rows: dict[str, dict[str, Any]] = {}

    def add(
        self,
        table: str,
        reason: str,
        raw: Mapping[str, Any],
        rec: FileRecord,
        source_row: int | None,
        *,
        season: int | None = None,
        candidates: Any = None,
        discriminator: str = "",
    ) -> None:
        qid = f"q:{_h(table, rec.path, source_row, reason, discriminator)}"
        self.rows[qid] = {
            "quarantine_id": qid,
            "table_name": table,
            "reason": reason,
            "candidates": None if candidates is None else json.dumps(candidates, sort_keys=True, default=str),
            "raw": json.dumps(raw, ensure_ascii=False, sort_keys=True),
            "season": season,
            "provenance": Provenance.LEGACY_IMPORT.value,
            "source_path": rec.path,
            "source_sha256": rec.sha256,
            "source_row": source_row,
        }


def _src(rec: FileRecord, row: int | None) -> dict[str, Any]:
    return {
        "provenance": Provenance.LEGACY_IMPORT.value,
        "source_path": rec.path,
        "source_sha256": rec.sha256,
        "source_row": row,
    }


def _csv_rows(rec: FileRecord) -> tuple[list[str], list[list[str]]]:
    text = rec.data.decode("utf-8-sig")
    reader = csv.reader(io.StringIO(text))
    header = next(reader, [])
    return header, [r for r in reader if r]


def _int(v: str | None) -> int | None:
    if v is None:
        return None
    v = v.strip()
    if re.fullmatch(r"-?\d+(\.0+)?", v):
        return int(v.split(".", 1)[0])
    return None


def _float(v: str | None) -> float | None:
    try:
        return float(v) if v not in (None, "") else None
    except ValueError:
        return None


def _date(v: str) -> date | None:
    try:
        return date.fromisoformat(v[:10]) if re.fullmatch(r"\d{4}-\d{2}-\d{2}", v[:10]) else None
    except ValueError:
        return None


