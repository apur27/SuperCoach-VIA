def _resolve_name(
    state: State,
    name: str,
    *,
    season_: int | None,
    club: str | None = None,
    reversed_order: bool = False,
    first_season_window: tuple[int, int] | None = None,
) -> str | None:
    """Unambiguous identity mapping or None. Never guesses between candidates."""
    variants = {ids.normalize_name(name)}
    if reversed_order:
        parts = ids.normalize_name(name).split(" ")
        if len(parts) >= 2:
            variants = {" ".join(parts[1:] + parts[:1]), " ".join(parts[-1:] + parts[:-1])}
    cands: set[str] = set()
    if club is not None and season_ is not None:
        names = state.club_season_names.get((season_, club), {})
        for v in variants:
            cands |= names.get(v, set())
    elif first_season_window is not None:
        lo, hi = first_season_window
        index = state.name_index()
        for v in variants:
            for pid in index.get(v, ()):
                fs = state.first_season.get(pid)
                if fs is not None and lo <= fs <= hi:
                    cands.add(pid)
    elif season_ is not None:
        index = state.name_index()
        active = state.season_players.get(season_, set())
        for v in variants:
            cands |= index.get(v, set()) & active
    return next(iter(cands)) if len(cands) == 1 else None


def _draft_club(state: State, name: str, year: int, rec: FileRecord) -> str | None:
    if not name.strip():
        return None
    # a draft held late in year Y serves season Y+1
    return state.clubs.resolve(name, year + 1) or state.clubs.resolve(name, year) or _club(state, name, year + 1, rec)


